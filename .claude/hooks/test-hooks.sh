#!/bin/bash
# Tests for the hooks in this folder (npm run test:hooks, part of npm run test:ci). Builds throwaway repos in a temp
# dir: an origin, "Harsh" pushing to main, and our branch. Nothing outside the temp dir is touched.
H="$(cd "$(dirname "$0")" && pwd)"
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
export GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL="$T/gitconfig" GH_TOKEN=none
git config --file "$T/gitconfig" init.defaultBranch main
git config --file "$T/gitconfig" advice.detachedHead false
pass=0; fail=0
ok()   { pass=$((pass + 1)); echo "  ok   $1"; }
bad()  { fail=$((fail + 1)); echo "  FAIL $1"; }
expect() { # expect <name> <wanted exit> <actual exit>
  if [ "$3" -eq "$2" ]; then ok "$1"; else bad "$1"; echo "       wanted exit $2, got $3"; fi
}
as_harsh() { git -C "$T/harsh" -c user.name=Harsh -c user.email=harsh@example.com "$@"; }
as_us()    { git -C "$W" -c user.name=Us -c user.email=us@example.com "$@"; }
bash_input() { jq -cn --arg c "$1" --arg d "$W" '{tool_name:"Bash",tool_input:{command:$c},cwd:$d}'; }
guard() { bash_input "$1" | CLAUDE_PROJECT_DIR="$W" "$H/guard-git.sh" >/dev/null 2>&1; echo $?; }

git init -q --bare "$T/origin.git"
git clone -q "$T/origin.git" "$T/harsh" 2>/dev/null
printf 'line 1\nline 2\nline 3\nline 4\nline 5\n' > "$T/harsh/app.js"
printf 'old 1\nold 2\n' > "$T/harsh/old.js"
as_harsh add -A
GIT_AUTHOR_DATE="$(($(date +%s) - 30 * 86400)) +0000" as_harsh commit -qm "start"
as_harsh push -q origin main
git clone -q "$T/origin.git" "$T/work"; W="$T/work"
as_us checkout -q -b feature origin/main

echo "stale branch"
as_harsh pull -q; echo "harsh line" >> "$T/harsh/app.js"; as_harsh commit -qam "harsh: new line"; as_harsh push -q
expect "commit blocked when the branch is behind origin/main" 2 "$(guard 'git commit -m x')"
expect "push blocked when behind" 2 "$(guard 'git push -u origin feature')"
expect "gh pr create blocked when behind" 2 "$(guard 'gh pr create --title x --body y')"
as_us merge -q --no-edit origin/main
expect "commit allowed after merging origin/main" 0 "$(guard 'git commit -m x')"
expect "push of the branch allowed when up to date and clean" 0 "$(guard 'git push -u origin feature')"
expect "other commands pass" 0 "$(guard 'ls -la && git status')"

echo "no rebase, force, reset --hard, keep-ours, push to main"
expect "git rebase blocked" 2 "$(guard 'git rebase origin/main')"
expect "git pull --rebase blocked" 2 "$(guard 'git pull --rebase origin main')"
expect "git push --force blocked" 2 "$(guard 'git push --force origin feature')"
expect "git push -f blocked" 2 "$(guard 'git push -f')"
expect "git push --force-with-lease blocked" 2 "$(guard 'git push --force-with-lease origin feature')"
expect "git push +refspec blocked" 2 "$(guard 'git push origin +feature')"
expect "git reset --hard blocked" 2 "$(guard 'git reset --hard origin/main')"
expect "git merge -X ours blocked" 2 "$(guard 'git merge -X ours origin/main')"
expect "git merge -s ours blocked" 2 "$(guard 'git merge -s ours origin/main')"
expect "git checkout --ours blocked" 2 "$(guard 'git checkout --ours app.js')"
expect "git push origin main blocked" 2 "$(guard 'git push origin main')"
expect "git push origin HEAD:main blocked" 2 "$(guard 'git push origin HEAD:main')"
expect "git push --follow-tags allowed" 0 "$(guard 'git push --follow-tags origin feature')"

echo "secrets"
expect "cat .env.local blocked" 2 "$(guard 'cat .env.local')"
expect "tail ~/kraffic-readonly.env blocked" 2 "$(guard 'tail ~/kraffic-readonly.env')"
expect "printenv blocked" 2 "$(guard 'printenv')"
expect "cat .env.example allowed" 0 "$(guard 'cat .env.example')"
expect "env names only allowed" 0 "$(guard "grep -oE '^[A-Z_]+=' .env.local")"

echo "server only through git"
expect "ssh to the server blocked" 2 "$(guard 'ssh root@203.0.113.5 "cd /var/www && git status"')"
expect "scp blocked" 2 "$(guard 'scp app.js root@203.0.113.5:/var/www/')"
expect "rsync to a host blocked" 2 "$(guard 'rsync -a . root@203.0.113.5:/var/www/')"
expect "a port-forward tunnel allowed" 0 "$(guard 'ssh -N -L 6543:localhost:5432 readonly@203.0.113.5')"

echo "AI attribution"
expect "commit with Co-Authored-By: Claude blocked" 2 "$(guard 'git commit -m "x

Co-Authored-By: Claude <noreply@anthropic.com>"')"
expect "PR body with Generated with Claude Code blocked" 2 "$(guard 'gh pr create --title x --body "Generated with [Claude Code]"')"
expect "PR body about AI engines allowed" 0 "$(guard 'git commit -m "Count answers generated by AI engines"')"
as_us commit -q --allow-empty -m "y

Co-authored-by: Cursor <cursoragent@cursor.com>"
expect "push blocked when a branch commit has AI attribution" 2 "$(guard 'git push -u origin feature')"
as_us reset -q --hard HEAD~1

echo "owner-only approvals"
expect "Claude can't run approve-merge.sh" 2 "$(guard '.claude/hooks/approve-merge.sh 12')"
expect "Claude can't write the approvals file" 2 "$(guard 'echo 12 abc >> .git/kraffic-approved-merges')"
w=$(jq -cn --arg p "$W/.git/kraffic-approved-merges" '{tool_name:"Write",tool_input:{file_path:$p,content:"x"}}' | "$H/guard-git.sh" >/dev/null 2>&1; echo $?)
expect "Write tool can't create the approvals file" 2 "$w"
w=$(jq -cn --arg p "$W/notes.md" '{tool_name:"Write",tool_input:{file_path:$p,content:"x"}}' | "$H/guard-git.sh" >/dev/null 2>&1; echo $?)
expect "Write tool on an ordinary file passes" 0 "$w"

echo "merge conflicts stop for the owner"
sed -i.bak 's/line 2/harsh line 2/' "$T/harsh/app.js" && rm "$T/harsh/app.js.bak"; as_harsh commit -qam "harsh: line 2"; as_harsh push -q
sed -i.bak 's/line 2/our line 2/' "$W/app.js" && rm "$W/app.js.bak"; as_us commit -qam "us: line 2"
as_us fetch -q; as_us merge --no-edit origin/main >/dev/null 2>&1
out=$(bash_input 'git merge origin/main' | "$H/conflict-stop.sh" 2>&1); s=$?
expect "conflict-stop says STOP after a conflicted merge" 2 "$s"
case "$out" in *app.js*) ok "the STOP message lists the conflicting file" ;; *) bad "the STOP message lists the conflicting file" ;; esac
expect "committing the conflicted merge blocked before the owner approves" 2 "$(guard 'git commit --no-edit')"
(cd "$W" && "$H/approve-merge.sh" conflicts >/dev/null)
bash_input 'git status' | "$H/conflict-stop.sh" >/dev/null 2>&1
expect "conflict-stop quiet once the owner approved" 0 "$?"
printf 'line 1\nharsh line 2\nline 3\nline 4\nline 5\nharsh line\n' > "$W/app.js"; as_us add app.js
expect "after approval, committing the merge is allowed (not counted as behind)" 0 "$(guard 'git commit --no-edit')"
as_us commit -q --no-edit

echo "lines other people touched"
base=$(as_us rev-parse origin/main)
sed -i.bak 's/harsh line 2/reverted line 2/' "$W/app.js" && rm "$W/app.js.bak"; as_us commit -qam "us: change harsh's line"
out=$(cd "$W" && "$H/others-lines.sh" origin/main HEAD 7); s=$?
expect "others-lines finds a line Harsh changed this week" 1 "$s"
case "$out" in *"app.js:2"*Harsh*) ok "it names the file, line and author" ;; *) bad "it names the file, line and author"; echo "$out" ;; esac
as_us rm -q old.js; as_us commit -qm "us: delete old.js"
out=$(cd "$W" && "$H/others-lines.sh" origin/main HEAD 7)
case "$out" in *old.js*) bad "a 30-day-old line isn't listed for 7 days" ;; *) ok "a 30-day-old line isn't listed for 7 days" ;; esac
out=$(cd "$W" && "$H/others-lines.sh" origin/main HEAD 0)
case "$out" in *"old.js:1"*) ok "with 0 days every age is listed (the 24h re-check)" ;; *) bad "with 0 days every age is listed (the 24h re-check)" ;; esac
git -C "$W" checkout -q -b mine-only "$base"; echo "our line" >> "$W/app.js"; as_us commit -qam "us: add"
sed -i.bak 's/our line/our line, edited/' "$W/app.js" && rm "$W/app.js.bak"; as_us commit -qam "us: edit our line"
(cd "$W" && "$H/others-lines.sh" origin/main HEAD 7 >/dev/null); expect "our own lines aren't listed" 0 "$?"
(cd "$W" && "$H/others-lines.sh" HEAD~5 origin/main >/dev/null 2>&1); expect "a head that doesn't contain the base can't be checked" 2 "$?"
git -C "$W" checkout -q feature

echo "merge approval"
head=$(as_us rev-parse HEAD)
(cd "$W" && "$H/merge-check.sh" origin/main "$head" 7 >/dev/null 2>&1); expect "gh pr merge blocked without the owner's approval" 2 "$?"
msg=$(cd "$W" && "$H/merge-check.sh" origin/main "$head" 7 2>&1)
case "$msg" in *"app.js:2"*) ok "the block lists the other author's lines for the owner" ;; *) bad "the block lists the other author's lines for the owner" ;; esac
echo "7 0000000000000000000000000000000000000000 1" >> "$W/.git/kraffic-approved-merges"
(cd "$W" && "$H/merge-check.sh" origin/main "$head" 7 >/dev/null 2>&1); expect "an approval for an older head doesn't count" 2 "$?"
echo "7 $head $(date +%s)" >> "$W/.git/kraffic-approved-merges"
(cd "$W" && "$H/merge-check.sh" origin/main "$head" 7 >/dev/null 2>&1); expect "merge allowed with the owner's approval at this head" 0 "$?"

echo "fetch and fast-forward main"
echo "more" >> "$T/harsh/app.js"; as_harsh commit -qam "harsh: more"; as_harsh push -q
out=$("$H/sync-main.sh" "$W"); s=$(git -C "$W" rev-parse main); r=$(git -C "$W" rev-parse origin/main)
[ "$s" = "$r" ] && ok "main fast-forwarded (not checked out)" || bad "main fast-forwarded (not checked out)"
case "$out" in *"STALE BRANCH"*) ok "warns that the branch is behind" ;; *) bad "warns that the branch is behind" ;; esac
case "$out" in *"OLD BRANCH"*others-lines.sh*) ok "asks for the re-check once main moved after the branch was made" ;; *) bad "asks for the re-check once main moved after the branch was made"; echo "$out" ;; esac
git clone -q "$T/origin.git" "$T/w2"
echo "even more" >> "$T/harsh/app.js"; as_harsh commit -qam "harsh: even more"; as_harsh push -q
"$H/sync-main.sh" "$T/w2" >/dev/null
[ "$(git -C "$T/w2" rev-parse main)" = "$(git -C "$T/w2" rev-parse origin/main)" ] && ok "checked-out clean main fast-forwarded" || bad "checked-out clean main fast-forwarded"
echo "dirty" >> "$T/w2/app.js"
echo "yet more" >> "$T/harsh/app.js"; as_harsh commit -qam "harsh: yet more"; as_harsh push -q
out=$("$H/sync-main.sh" "$T/w2")
[ "$(git -C "$T/w2" rev-parse main)" != "$(git -C "$T/w2" rev-parse origin/main)" ] && ok "main with uncommitted changes left alone" || bad "main with uncommitted changes left alone"
case "$out" in *"uncommitted changes"*) ok "and it says so" ;; *) bad "and it says so" ;; esac

echo "idle check"
stamp="$W/.git/kraffic-last-prompt"
date +%s > "$stamp"
out=$(jq -cn --arg d "$W" '{cwd:$d,prompt:"hi"}' | "$H/prompt-sync.sh")
[ -z "$out" ] && ok "no fetch within 30 minutes" || bad "no fetch within 30 minutes"
echo $(( $(date +%s) - 1801 )) > "$stamp"
out=$(jq -cn --arg d "$W" '{cwd:$d,prompt:"hi"}' | "$H/prompt-sync.sh")
case "$out" in *Idle*Branch:*) ok "fetches again after 30 minutes idle" ;; *) bad "fetches again after 30 minutes idle"; echo "$out" ;; esac

echo "$pass passed, $fail failed"
[ "$fail" -eq 0 ]
